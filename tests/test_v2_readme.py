def test_the_checker_catches_what_it_is_meant_to():
    # The README keeps failing these silently if the checks above go slack.
    good = "# T\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n[t](#t)\n"
    _assert_well_formed(good)
    for bad in (
        good.replace("(#t)", "(#nowhere)"),
        good.replace("| 1 | 2 |", "| 1 | 2 | 3 |"),
        good.replace("|---|---|\n", ""),
        good.replace("| 1 | 2 |\n", "| 1 | 2 |\n\n| 3 | 4 |\n"),
        good + "```\nopen\n",
        good + "{{ left }}\n",
        good.replace("| 1 | 2 |", "| `a|b` | 2 |"),
    ):
        with pytest.raises(AssertionError):
            _assert_well_formed(bad)


