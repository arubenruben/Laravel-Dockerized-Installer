# ── A small Markdown reader: just what the checks below need ──────────────────


def _outside_fences(text: str):
    """Yield ``(line, in_fence)`` for every line; the fence lines themselves are ``in_fence``."""
    in_fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            yield line, True
            in_fence = not in_fence
        else:
            yield line, in_fence


def _slug(heading: str) -> str:
    """GitHub's anchor for a heading."""
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def _split_row(row: str) -> list[str]:
    """The cells of a table row. Like GitHub, only ``\\|`` keeps a pipe inside a cell."""
    assert row.startswith("|") and row.rstrip().endswith("|"), f"not a table row: {row!r}"
    return [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", row.strip())[1:-1]]


def _tables(text: str) -> list[list[list[str]]]:
    """Every table outside code fences, as a list of rows of cells (header and separator included)."""
    tables: list[list[list[str]]] = []
    current: list[list[str]] = []
    for line, in_fence in _outside_fences(text):
        if not in_fence and line.startswith("|"):
            current.append(_split_row(line))
        else:
            if current:
                tables.append(current)
            current = []
    if current:
        tables.append(current)
    return tables


def _section(text: str, heading: str) -> str:
    """The text under ``heading`` (e.g. ``"## Stack"``), up to the next heading of the same or a higher level."""
    level = len(heading.split()[0])
    collected: list[str] = []
    inside = False
    for line, in_fence in _outside_fences(text):
        found = None if in_fence else re.match(r"(#+) ", line)
        if found and inside and len(found.group(1)) <= level:
            break
        if line == heading and not in_fence:
            inside = True
        elif inside:
            collected.append(line)
    assert inside, f"no {heading!r} heading"
    return "\n".join(collected)


def _table_rows(text: str, heading: str) -> list[list[str]]:
    """The body rows of the first table under ``heading``."""
    return _tables(_section(text, heading))[0][2:]


def _assert_well_formed(readme: str) -> None:
    assert not re.search(r"\{\{|\{%|\{#|%\}|#\}", readme), "unrendered template syntax"
    fences = [line for line in readme.splitlines() if line.startswith("```")]
    assert len(fences) % 2 == 0, "unbalanced code fence"

    for table in _tables(readme):
        assert len(table) >= 2, f"table without a separator row: {table}"
        header, separator, *rows = table
        assert all(re.fullmatch(r":?-+:?", cell) for cell in separator), f"no separator row under {header}"
        for row in rows:
            assert len(row) == len(header), f"{len(row)} cells under a {len(header)}-column header: {row}"

    anchors = {
        _slug(match.group(2))
        for line, in_fence in _outside_fences(readme)
        if not in_fence and (match := re.match(r"(#+) (.+)", line))
    }
    for target in re.findall(r"\]\(#([^)]+)\)", readme):
        assert target in anchors, f"link to #{target}, which is not a heading"


