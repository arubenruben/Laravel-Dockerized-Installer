@pytest.mark.parametrize("db", DBS)
@pytest.mark.parametrize(("queue", "horizon"), QUEUES)
def test_stack_table_images_and_ports_are_the_ones_in_the_compose_files(client, db, queue, horizon):
    archive = _get_project(client, **_combo(db, queue, horizon, None, php_version="8.3", app_port="9090"))
    rows = _stack_rows(_text(archive, "README.md"))
    dev = yaml.safe_load(_text(archive, "docker-compose.yml"))["services"]
    dockerfile = _text(archive, "Dockerfile")

    for name, service in dev.items():
        _, image, dev_cell, _ = rows[name]
        ports = [str(port).split(":")[0] for port in service.get("ports", [])]
        # The dev column names every published host port, and says so only when there is one.
        assert all(port in dev_cell for port in ports), (name, ports, dev_cell)
        assert ("host port" in dev_cell) == bool(ports), (name, dev_cell)

        if "build" in service:
            assert dockerfile.startswith("FROM php:8.3-fpm-alpine\n")
            assert "php:8.3-fpm-alpine" in image
        elif name == "worker":
            assert service["image"] == dev["app"]["image"] and image == "same image as app"
        elif name == "vite":
            assert image.startswith(f"{service['image']},") and service["image"] == "php:8.3-cli-alpine"
            assert "apk add --no-cache nodejs npm" in service["command"]
        else:
            assert image == service["image"], name


